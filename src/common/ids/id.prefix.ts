/**
 * The prefixes payzeno-api owns. domain-model.md §0.2 is the full cross-service table.
 *
 * These are NOT the `ID_PREFIXES` table in @payzeno/contracts, and must not be named as if they
 * were.
 * That table is keyed by the bare prefix (`mch`) and carries owner metadata for all twenty
 * prefixes in the platform; this one is keyed by entity name, carries the separator (`mch_`)
 * because every call site concatenates, and covers only what we mint. Two shapes for two jobs
 * — but for a while they had the same name, and a file that needed both could not import both.
 *
 * What is deliberately NOT reimplemented here is the ULID body check. That is `isUlid` from the
 * contracts package, which also rejects a first character above '7': the first character encodes
 * the top three bits of a 48-bit millisecond timestamp, so anything higher is a malformed id
 * rather than a far-future one. The regex this file used to carry accepted those.
 */
import { isUlid } from '@payzeno/contracts/ids';

export const API_ID_PREFIXES = {
  merchant: 'mch_',
  user: 'usr_',
  apiKey: 'key_',
  bankAccount: 'ba_',
  paymentIntent: 'pi_',
  charge: 'ch_',
  refund: 're_',
  dispute: 'dp_',
  webhookEvent: 'evt_',
  checkoutSession: 'cs_',
} as const;

export type ApiIdPrefix = (typeof API_ID_PREFIXES)[keyof typeof API_ID_PREFIXES];

/**
 * Ids minted elsewhere but stored/validated here. Never generated by payzeno-api.
 *
 * `stf_` is the one entry with no counterpart in the contracts table: staff users are internal
 * to payzeno-api and no other service ever sees the id, so it was never worth freezing.
 */
export const FOREIGN_ID_PREFIXES = {
  account: 'acct_',
  ledgerTransaction: 'txn_',
  settlementBatch: 'sb_',
  reconciliationItem: 'ri_',
  payout: 'po_',
  invoice: 'inv_',
  staffUser: 'stf_',
  paymentMethodToken: 'pmt_',
  bankAccountToken: 'bat_',
} as const;

export const ALL_PREFIXES: readonly string[] = [
  ...Object.values(API_ID_PREFIXES),
  ...Object.values(FOREIGN_ID_PREFIXES),
];

export function isPayzenoId(value: unknown, prefix?: string): value is string {
  if (typeof value !== 'string') return false;

  const matched = prefix ? (value.startsWith(prefix) ? prefix : null) : ALL_PREFIXES.find((p) => value.startsWith(p));
  if (!matched) return false;

  return isUlid(value.slice(matched.length));
}

export function prefixOf(value: string): string | null {
  return ALL_PREFIXES.find((p) => value.startsWith(p)) ?? null;
}
